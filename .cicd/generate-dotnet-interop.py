"""Generate blittable .NET declarations from the public C ABI, without third-party tooling."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / 'Sources/XmaxSDK.Net/Interop'


def generate():
    source = re.sub(r'/\*.*?\*/', '', (ROOT / 'include/xmax/xmax.h').read_text(), flags=re.S)
    handles = set(re.findall(r'typedef struct \w+\* (xmax_\w+);', source))
    enums = set(re.findall(r'typedef enum (\w+)', source))
    callbacks = set(re.findall(r'typedef void\(XMAX_CALL\* (\w+)\)', source))
    aliases = {'void': 'void', 'char': 'byte', 'uint8_t': 'byte', 'uint32_t': 'uint',
               'int32_t': 'int', 'uint64_t': 'ulong', 'int64_t': 'long', 'size_t': 'nuint',
               'double': 'double', 'float': 'float', 'xmax_result': 'int'}

    def cs_type(value):
        value = re.sub(r'\bconst\b', '', value).strip()
        pointers = value.count('*')
        value = value.replace('*', '').strip()
        base = 'nint' if value in handles or value in callbacks else 'int' if value in enums else aliases.get(value, value)
        return base + '*' * pointers

    prefix = '// <auto-generated> .cicd/generate-dotnet-interop.py; source: include/xmax/xmax.h </auto-generated>\n'
    types = [prefix, 'using System.Runtime.InteropServices;\nnamespace Xmax.SDK.Interop;\n']
    probe = ['/* Generated by .cicd/generate-dotnet-interop.py. */', '#include <xmax/xmax.h>', '#include <stddef.h>', '#include <stdio.h>', 'int main(void) {']
    # Compile enum values from the header so managed event routing is checked alongside layout.
    for managed, native in [('State', 'STATE'), ('Error', 'ERROR'), ('Statistics', 'STATISTICS'),
                            ('Timing', 'TIMING'), ('Quality', 'QUALITY_CHANGE'), ('Performance', 'PERFORMANCE')]:
        probe.append(f'    printf("enum RealtimeEventType {managed} %d\\n", XMAX_EVENT_{native});')
    for name, body in re.findall(r'typedef struct (xmax_\w+)\s*\{(.*?)\}\s*\1;', source, re.S):
        probe.append(f'    printf("sizeof {name} %zu\\n", sizeof({name}));')
        types += ['[StructLayout(LayoutKind.Sequential, Pack = 8)]', f'internal unsafe struct {name}', '{']
        for declaration in body.split(';'):
            declaration = declaration.strip()
            if not declaration:
                continue
            match = re.fullmatch(r'(.+?)\s+(\w+)(?:\[(\d+)\])?', declaration, re.S)
            if not match:
                raise ValueError(f'Unrecognized field: {declaration}')
            ctype, field, count = match.groups()
            ctype = cs_type(ctype)
            if count and ctype in {'byte', 'int', 'uint', 'long', 'ulong', 'double', 'float'}:
                types.append(f'    public fixed {ctype} @{field}[{count}];')
                probe.append(f'    printf("offsetof {name} {field} %zu\\n", offsetof({name}, {field}));')
            elif count:
                types += [f'    public {ctype} {field}_{i};' for i in range(int(count))]
                probe += [f'    printf("offsetof {name} {field}_{i} %zu\\n", offsetof({name}, {field}) + {i} * sizeof((({name}*)0)->{field}[0]));' for i in range(int(count))]
            else:
                types.append(f'    public {ctype} @{field};')
                probe.append(f'    printf("offsetof {name} {field} %zu\\n", offsetof({name}, {field}));')
        types.append('}\n')

    methods = [prefix, 'using System.Runtime.CompilerServices;', 'using System.Runtime.InteropServices;',
               'namespace Xmax.SDK.Interop;', 'internal static unsafe partial class NativeMethods', '{',
               '    internal const string Library = "XmaxSDK";']
    functions = re.findall(r'^XMAX_API\s+((?:const\s+)?\w+\s*\*?)\s+XMAX_CALL\s+(xmax_\w+)\s*\((.*?)\)\s*;', source, re.S | re.M)
    declared = set(re.findall(r'XMAX_CALL\s+(xmax_\w+)\s*\(', source))
    if declared != {name for _, name, _ in functions}:
        raise ValueError('A public C function could not be generated')
    for result, name, args in functions:
        parameters = []
        for arg in args.split(','):
            arg = arg.strip()
            if arg in {'', 'void'}:
                continue
            match = re.fullmatch(r'(.+?)\s+(\w+)', arg, re.S)
            if not match:
                raise ValueError(f'Unrecognized parameter: {arg}')
            parameters.append(f'{cs_type(match[1])} @{match[2]}')
        methods += ['    [LibraryImport(Library)]', '    [UnmanagedCallConv(CallConvs = [typeof(CallConvCdecl)])]',
                    f'    internal static partial {cs_type(result)} {name}({", ".join(parameters)});']
    methods.append('}\n')
    probe += ['    return 0;', '}\n']
    return {'NativeTypes.g.cs': '\n'.join(types), 'NativeMethods.g.cs': '\n'.join(methods),
            str(ROOT / 'Tests/XmaxSDKNetTests/native_abi_probe.c'): '\n'.join(probe)}


if __name__ == '__main__':
    for name, content in generate().items():
        path = DEST / name
        if '--check' in sys.argv:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Stale .NET interop: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print('.NET interop matches public C ABI')
